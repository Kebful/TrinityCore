#ifndef TRINITYCORE_FFXIV_COMBAT_TABLES_H
#define TRINITYCORE_FFXIV_COMBAT_TABLES_H

#include "Define.h"

/*
 * Published FFXIV combat constants, kept in one generated data file.
 *
 * The data lives in FFXIVCombatTables.inc, which is GENERATED by
 * work/stat-research/gen_ffxiv_combat_tables.py from the cited sources -- never
 * edit it by hand. ValidateFfxivCombatTables() pins every anchor and every
 * structural invariant at first use, so a hand-edited or regenerated table
 * aborts loudly instead of quietly changing damage.
 *
 * What is data (this file) and what is formula (FFXIVCombatMath.cpp):
 *   f(AP) coefficient per level and role     B §F23.3, §F24.7, I §9.3
 *   f(HMP) divisor per level                 B §F23.4 (published at 70/80 only)
 *   job -> attribute / trait / auto / DoT    B §F23.13, §F24.2, I §9.5
 * Everything else in the chain (100/1400/550/140/112/200/130, the ±5 % and
 * ±3 % variance bands, the -2.5 % level correction, 90/80 auto potency) is a
 * published *coefficient* and lives as a named constant next to the formula in
 * FFXIVCombatMath.h, not here.
 *
 * Every per-level row carries its own provenance bit. "Interpolated" and "held"
 * rows are the UNKNOWNs of B §F24.7 / I §8.4 -- they are marked, not hidden.
 */

namespace FFXIV::Combat
{
constexpr uint8 FFXIV_COMBAT_LEVEL_COUNT = 100; // levels 1..100
constexpr uint8 FFXIV_COMBAT_JOB_COUNT = 44;    // ClassJob rows 0..43

// Provenance bits for a per-level row (FfxivCombatProvenance).
enum FfxivCombatProvenance : uint8
{
    // f(AP): the coefficient is an anchor taken verbatim from a cited source
    FFXIV_COMBAT_AP_SOURCED = 0x1,
    // f(AP): the published 5.x Lv1-50 flat band (75), not a per-level anchor
    FFXIV_COMBAT_AP_PUBLISHED_BAND = 0x2,
    // f(AP): linearly interpolated between two anchors -- UNKNOWN until calibrated
    FFXIV_COMBAT_AP_INTERPOLATED = 0x4,
    // f(AP): no data at this level, the nearest anchor is held constant -- UNKNOWN
    FFXIV_COMBAT_AP_HELD = 0x8,
    // f(HMP): the divisor is published for this level (B §F23.4)
    FFXIV_COMBAT_HMP_SOURCED = 0x10,
    // f(HMP): divisor held from the nearest published level -- UNKNOWN
    FFXIV_COMBAT_HMP_HELD = 0x20,
};

// f(AP) = floor(coefficient * (stat - MAIN) / MAIN) + 100, MAIN = level base main
// stat. `nonTank` and `tank` are the two role series (§9.3: tank 190 / other 237
// at L100). Below L50 the tank series has no published value; those rows hold the
// L50 anchor and say so.
struct FfxivAttackPowerRow
{
    uint8 level;
    int16 nonTank;
    int16 tank;
    uint8 provenance;      // nonTank series, FfxivCombatProvenance
    uint8 tankProvenance;  // tank series, FfxivCombatProvenance
};

// f(HMP) = floor(100 * (HMP - MAIN) / divisor) + 100. Published divisors: Lv70
// 264, Lv80 304 (B §F23.4). No other level has a published value.
struct FfxivHealingPotencyRow
{
    uint8 level;
    uint16 divisor;
    uint8 provenance;
};

// DoT order of operations (B §F13.1/§F23.7): the two published branches differ.
enum FfxivDotDamageType : uint8
{
    FFXIV_DOT_PHYSICAL = 0,
    FFXIV_DOT_MAGICAL = 1,
};

// Per-job combat identity. `attributeParam` is the BaseParam row (FFXIV_PARAM_*)
// the job's Attack Power reads (B §F23.13); `damageTraitPercent` is the published
// 100/120/130/150 trait multiplier (B §F24.2, I §9.5) and is never applied to
// auto-attacks; `autoAttackPotency` is 90 melee / 80 ranged for 7.x (B §F24.2);
// `dotType` is the job's default DoT branch (B §F23.7) -- INFERRED from the job,
// because the real split is by damage type and the action's own type is not in
// any server-side table yet.
struct FfxivJobCombatRow
{
    uint8 jobId;
    char const* abbreviation;
    uint8 attributeParam;
    uint16 damageTraitPercent;
    uint8 autoAttackPotency;
    uint8 dotType;
};

FfxivAttackPowerRow const& GetFfxivAttackPowerRow(uint8 level);
FfxivHealingPotencyRow const& GetFfxivHealingPotencyRow(uint8 level);
FfxivJobCombatRow const& GetFfxivJobCombatRow(uint8 jobId);

// Recomputes the anchors and structural invariants from the compiled arrays.
// Idempotent, aborts (ABORT_MSG) on any mismatch. The accessors call it first.
void ValidateFfxivCombatTables();
} // namespace FFXIV::Combat

#endif // TRINITYCORE_FFXIV_COMBAT_TABLES_H
