#ifndef TRINITYCORE_FFXIV_STATUS_H
#define TRINITYCORE_FFXIV_STATUS_H

#include "Define.h"
#include <vector>

class Unit;
class Player;

/*
 * FFXIV statuses on the WoW aura container.
 *
 * Every FFXIV status is one aura spell (release/modules/ffxivhaven/datascripts/classes/spells/
 * ffxiv-statuses.ts, generated by tools/generate-ffxiv-statuses.py). The world table `ffxiv_status`
 * maps the retail Status id to that spell and carries the rules the aura row cannot:
 *
 *     statusId       retail Status row id
 *     spellId        the aura spell
 *     duration       ms; the status's default, 0 when the sheets state no single default
 *     maxStacks      Status col 4 (+0x15); 0 = does not stack
 *     refreshPolicy  FfxivStatusRefreshPolicy; no sheet states it, the module writes Reset
 *     flags          FfxivStatusFlag, one Status column each
 *
 * `ffxiv_action_status` (actionId, statusId, duration, comboOnly) holds each duration an action's
 * ActionTransient text states: the duration belongs to the action, not the status (Stun is 4 s
 * from Holy and 6 s from Shield Bash). comboOnly is 1 when the action's text grants the status only
 * on a line that starts "Combo Bonus:" (Storm's Eye -> Surging Tempest, Disembowel -> Power Surge):
 * such a status is applied only when the cast was the correct step of its combo chain
 * (Combat::WasFfxivCorrectComboStep, the same test the job gauge's comboOnly rows use).
 *
 * An empty or missing table changes nothing: every lookup misses and ApplyFfxivStatus returns false
 * without touching the target.
 *
 * Intended call site (the action path, owned by the combat slice), once per status the action
 * applies, with the unit that status goes to:
 *
 *     FFXIV::Status::ApplyFfxivStatus(target, statusId, caster,
 *                                     FFXIV::Status::GetFfxivActionStatusDuration(actionId, statusId));
 *
 * Implemented as ApplyFfxivActionStatuses below and called from Spell::EffectDummy (the module ships
 * every Action as one DUMMY effect), before the potency hook: a pure buff such as Inner Release 7389
 * has no potency row, so the damage hook returns early and would never apply it.
 * Not in this slice: ticks (a DoT's potency), the Lock* flags (recorded, not enforced), and the
 * player's click-off packet (CMSG_CANCEL_AURA keeps its WoW rule; RequestRemoveFfxivStatus is the
 * sheet rule for it).
 */

namespace FFXIV::Status
{
// What a re-apply by the same source does to the timer. The client replaces the timer on a same
// (id, source) re-apply (SPELL-CLOSE4-STATUSAPPLY §5), which is Reset; Extend is carried for rows a
// later slice authors, no sheet sets it.
enum class FfxivStatusRefreshPolicy : uint8
{
    Reset  = 0, // remaining = the new duration
    Extend = 1, // remaining += the new duration
};

constexpr uint8 FFXIV_STATUS_REFRESH_POLICY_MAX = 1;

// One bit per Status sheet column (column numbers are the EXH order).
enum FfxivStatusFlag : uint32
{
    FFXIV_STATUS_FLAG_DEBUFF         = 0x01, // StatusCategory (col 6) == 2
    FFXIV_STATUS_FLAG_PERMANENT      = 0x02, // IsPermanent (col 18): no timer, lasts until removed
    FFXIV_STATUS_FLAG_CAN_STATUS_OFF = 0x04, // CanStatusOff (col 25): the bearer may remove it
    FFXIV_STATUS_FLAG_CAN_DISPEL     = 0x08, // CanDispel (col 15)
    FFXIV_STATUS_FLAG_LOCK_MOVEMENT  = 0x10, // LockMovement (col 9)
    FFXIV_STATUS_FLAG_LOCK_ACTIONS   = 0x20, // LockActions (col 11)
    FFXIV_STATUS_FLAG_LOCK_CONTROL   = 0x40, // LockControl (col 12)
};

constexpr int32 FFXIV_STATUS_UNTIL_REMOVED = -1; // the aura container's "no timer"

// One ffxiv_status row.
struct FfxivStatusRow
{
    uint32 statusId = 0;
    uint32 spellId = 0;
    int32 duration = 0;
    uint8 maxStacks = 0;
    uint8 refreshPolicy = 0; // FfxivStatusRefreshPolicy
    uint32 flags = 0;        // FfxivStatusFlag

    bool HasFlag(uint32 flag) const { return (flags & flag) != 0; }
};

// One ffxiv_action_status row.
struct FfxivActionStatusRow
{
    uint32 actionId = 0;
    uint32 statusId = 0;
    int32 duration = 0;
    bool comboOnly = false; // granted only by a correct combo step ("Combo Bonus: Grants ...")
};

// --- table access ---------------------------------------------------------------------------

// Startup load from the world database. A missing or empty table logs once and leaves it empty.
void LoadFfxivStatusTables();

// Replace / clear the tables (the loader and tests use these).
void SetFfxivStatusTables(std::vector<FfxivStatusRow> statuses, std::vector<FfxivActionStatusRow> actionStatuses);
void ClearFfxivStatusTables();

// The row for a status, or nullptr when the table does not carry it.
FfxivStatusRow const* GetFfxivStatus(uint32 statusId);

// The duration the action's text states for this status, or 0 (the status's default applies).
int32 GetFfxivActionStatusDuration(uint32 actionId, uint32 statusId);

// The statuses ffxiv_action_status lists for the action, in table order; nullptr when it lists none.
std::vector<uint32> const* GetFfxivActionStatuses(uint32 actionId);

// True when the action grants the status only on a correct combo step (the row's comboOnly column).
bool IsFfxivActionStatusComboOnly(uint32 actionId, uint32 statusId);

// The combo rule for one listed status: a plain row always applies, a comboOnly row applies only when
// `comboCorrect` (the cast was the correct step of its chain). Pure; ApplyFfxivActionStatuses asks it.
bool ShouldApplyFfxivActionStatus(uint32 actionId, uint32 statusId, bool comboCorrect);

// Apply every status the action lists (a comboOnly one only after a correct combo step: the damage hook of the same
// EffectDummy has already advanced the chain), from `caster`, using the action's stated duration. `effectTarget` is the unit the
// action's effect resolved on (the caster for a self effect, the enemy/ally for a targeted one): a debuff goes there, a
// buff goes there only when it is friendly, else to the caster. A caster buff is applied once per cast (an area effect
// calls its dummy effect once per target), so a stacking buff does not gain a stack per target.
// Returns the number of statuses the container accepted. The gate is the table: no row, no apply.
int ApplyFfxivActionStatuses(Player& caster, Unit& effectTarget, uint32 actionId);

// --- the rule (pure) --------------------------------------------------------------------------

// The state of one status on one target from one source, as the aura container holds it.
struct FfxivStatusInstance
{
    uint8 stacks = 0;
    int32 duration = 0;    // remaining ms, FFXIV_STATUS_UNTIL_REMOVED for no timer
    int32 maxDuration = 0; // the full timer the client draws against
};

enum class FfxivStatusApplyOutcome : uint8
{
    Rejected = 0, // no duration to apply (no default, none passed, not permanent)
    Added,
    Refreshed,
};

struct FfxivStatusApplyResult
{
    FfxivStatusApplyOutcome outcome = FfxivStatusApplyOutcome::Rejected;
    FfxivStatusInstance instance;
};

// The instance an apply produces. `existing` is the same source's instance on the target, or
// nullptr. `durationMs` > 0 overrides the row's default, < 0 means until removed, 0 takes the row.
// One apply adds one stack, capped at maxStacks (a non-stacking status stays at 1); the timer follows
// the row's refresh policy, at the cap too.
FfxivStatusApplyResult ResolveFfxivStatusApply(FfxivStatusRow const& row, FfxivStatusInstance const* existing,
                                               int32 durationMs);

// Counts the timer down the way the aura container does (Aura::Update). False once it expired.
bool AdvanceFfxivStatus(FfxivStatusInstance& instance, uint32 diffMs);

// --- the aura container ---------------------------------------------------------------------

// One (target, source) pair's view of the aura container. The Unit implementation is in
// FFXIVStatus.cpp; tests substitute their own.
class FfxivStatusContainer
{
public:
    virtual ~FfxivStatusContainer() = default;

    virtual bool Find(uint32 spellId, FfxivStatusInstance& instance) const = 0;
    virtual bool Add(uint32 spellId, FfxivStatusInstance const& instance) = 0;
    virtual void Update(uint32 spellId, FfxivStatusInstance const& instance) = 0;
    virtual void Remove(uint32 spellId) = 0;
};

bool ApplyFfxivStatusTo(FfxivStatusContainer& container, uint32 statusId, int32 durationMs = 0);
bool RequestRemoveFfxivStatusFrom(FfxivStatusContainer& container, uint32 statusId);

// --- API ------------------------------------------------------------------------------------

// Applies the status to `target` from `source` (the target itself when null). False, with the target
// untouched, when the table does not carry the status, its spell is missing or no duration applies.
bool ApplyFfxivStatus(Unit* target, uint32 statusId, Unit* source, int32 durationMs = 0);

// The bearer asks to drop the status (the retail "status off"). Only a CanStatusOff status goes.
bool RequestRemoveFfxivStatus(Unit* target, uint32 statusId, Unit* source);
}

#endif
